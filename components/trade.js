// Generate Static / Dynamic mock Order Book
let baseBids = [];
let baseAsks = [];
function generateOrderBook() {
    const ticker = state.tickers[activeTradingPair];
    const price = ticker.price;
    
    baseBids = [];
    baseAsks = [];

    // Generate 8 asks slightly above current price
    for (let i = 1; i <= 8; i++) {
        const askPrice = price * (1 + (i * 0.0003));
        const amount = Math.random() * 2.5 + 0.01;
        baseAsks.push({ price: askPrice, amount: amount });
    }

    // Generate 8 bids slightly below current price
    for (let i = 1; i <= 8; i++) {
        const bidPrice = price * (1 - (i * 0.0003));
        const amount = Math.random() * 2.5 + 0.01;
        baseBids.push({ price: bidPrice, amount: amount });
    }

    renderOrderBookDOM();
}

function renderOrderBookDOM() {
    const asksContainer = document.getElementById('ob-asks');
    const bidsContainer = document.getElementById('ob-bids');
    if (!asksContainer || !bidsContainer) return;

    // Red Asks Rows
    let asksHTML = '';
    let cumulativeAskTotal = 0;
    
    // Accumulate for depth shading
    const maxAskTotal = baseAsks.reduce((sum, item) => sum + item.amount, 0);
    
    baseAsks.forEach(ask => {
        cumulativeAskTotal += ask.amount;
        const total = ask.price * ask.amount;
        const percentage = Math.min((cumulativeAskTotal / maxAskTotal) * 100, 100);
        
        asksHTML += `
            <div class="ob-row" onclick="fillFormPrice(${ask.price})">
                <div class="depth-bar bg-red" style="width: ${percentage}%;"></div>
                <span class="price-col text-red">${ask.price.toFixed(2)}</span>
                <span>${ask.amount.toFixed(4)}</span>
                <span>${total.toFixed(2)}</span>
            </div>
        `;
    });
    asksContainer.innerHTML = asksHTML;

    // Green Bids Rows
    let bidsHTML = '';
    let cumulativeBidTotal = 0;
    const maxBidTotal = baseBids.reduce((sum, item) => sum + item.amount, 0);

    baseBids.forEach(bid => {
        cumulativeBidTotal += bid.amount;
        const total = bid.price * bid.amount;
        const percentage = Math.min((cumulativeBidTotal / maxBidTotal) * 100, 100);
        
        bidsHTML += `
            <div class="ob-row" onclick="fillFormPrice(${bid.price})">
                <div class="depth-bar bg-green" style="width: ${percentage}%;"></div>
                <span class="price-col text-green">${bid.price.toFixed(2)}</span>
                <span>${bid.amount.toFixed(4)}</span>
                <span>${total.toFixed(2)}</span>
            </div>
        `;
    });
    bidsContainer.innerHTML = bidsHTML;
}

window.fillFormPrice = function(price) {
    const buyPriceInput = document.getElementById('buy-price');
    const sellPriceInput = document.getElementById('sell-price');
    
    if (buyPriceInput) buyPriceInput.value = price.toFixed(2);
    if (sellPriceInput) sellPriceInput.value = price.toFixed(2);
    
    // Update math calculations
    const buyAmt = document.getElementById('buy-amount');
    const buyTot = document.getElementById('buy-total');
    if (buyAmt && buyAmt.value) {
        buyTot.value = (parseFloat(buyAmt.value) * price).toFixed(2);
    }
    const sellAmt = document.getElementById('sell-amount');
    const sellTot = document.getElementById('sell-total');
    if (sellAmt && sellAmt.value) {
        sellTot.value = (parseFloat(sellAmt.value) * price).toFixed(2);
    }
};

// Generate Mock Trades Feed
let tradesFeed = [];
function generateTradeFeed() {
    const feedContainer = document.getElementById('trade-history-feed');
    if (!feedContainer) return;

    const ticker = state.tickers[activeTradingPair];
    const price = ticker.price;
    tradesFeed = [];

    // Create 15 starter trades
    for (let i = 0; i < 20; i++) {
        const pctOffset = (Math.random() - 0.5) * 0.001;
        const tradePrice = price * (1 + pctOffset);
        const amount = Math.random() * 1.8 + 0.002;
        const side = Math.random() > 0.48 ? 'Buy' : 'Sell';
        
        // Random time offset
        const d = new Date();
        d.setSeconds(d.getSeconds() - (i * 3));
        const timeStr = d.toTimeString().split(' ')[0];

        tradesFeed.push({
            price: tradePrice,
            amount: amount,
            side: side,
            time: timeStr
        });
    }

    renderTradeFeedDOM();
}

function renderTradeFeedDOM() {
    const feedContainer = document.getElementById('trade-history-feed');
    if (!feedContainer) return;

    let html = '';
    tradesFeed.forEach(t => {
        html += `
            <div class="mt-row">
                <span class="price-col ${t.side === 'Buy' ? 'text-green' : 'text-red'}">${t.price.toFixed(2)}</span>
                <span>${t.amount.toFixed(5)}</span>
                <span class="time-col">${t.time}</span>
            </div>
        `;
    });
    feedContainer.innerHTML = html;
}

