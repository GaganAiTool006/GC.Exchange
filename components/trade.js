window.initTrade = function(params) {
    activeFormTab = 'limit';
    activeUserTab = 'open-orders';
    
    // Set up TradingView Chart
    initTradingViewChart();

    // Wire dropdown pair selector
    const pairSelector = document.getElementById('trade-pair-selector');
    if (pairSelector) {
        pairSelector.addEventListener('change', (e) => {
            window.location.hash = `#trade?pair=${encodeURIComponent(e.target.value)}`;
        });
    }

    // Tab buttons for forms (Limit / Market)
    const limitTab = document.getElementById('tab-trade-limit');
    const marketTab = document.getElementById('tab-trade-market');
    
    if (limitTab && marketTab) {
        limitTab.addEventListener('click', () => {
            activeFormTab = 'limit';
            limitTab.classList.add('active');
            marketTab.classList.remove('active');
            
            document.getElementById('buy-price-group').classList.remove('hidden');
            document.getElementById('sell-price-group').classList.remove('hidden');
            document.getElementById('buy-market-indicator').classList.add('hidden');
            document.getElementById('sell-market-indicator').classList.add('hidden');
            clearFormAmounts();
        });
        marketTab.addEventListener('click', () => {
            activeFormTab = 'market';
            marketTab.classList.add('active');
            limitTab.classList.remove('active');
            
            document.getElementById('buy-price-group').classList.add('hidden');
            document.getElementById('sell-price-group').classList.add('hidden');
            document.getElementById('buy-market-indicator').classList.remove('hidden');
            document.getElementById('sell-market-indicator').classList.remove('hidden');
            clearFormAmounts();
        });
    }

    // Set up initial form validation listeners and math converters
    setupTradeFormMath();

    // Setup bottom panels (open orders, history, funds)
    document.querySelectorAll('.panel-tab-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            document.querySelectorAll('.panel-tab-btn').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            activeUserTab = btn.dataset.tab;
            renderUserPanelContent();
        });
    });

    // Populate balances
    updateTradeAvblBalances();

    // Generate Initial Order Book
    generateOrderBook();

    // Generate Mock Feed
    generateTradeFeed();

    // Draw user dashboards
    renderUserPanelContent();

    // Wire custom tickers updates
    window.addEventListener('tickerUpdate', handleLiveTickersTrade);
}

// Draw TradingView widget inside viewport
function initTradingViewChart() {
    const container = document.getElementById('tradingview-container');
    if (!container) return;

    const baseSymbol = activeTradingPair.split('/')[0];
    
    // Clear out container first
    container.innerHTML = `<div id="tradingview_chart" style="width: 100%; height: 100%;"></div>`;

    if (window.TradingView) {
        try {
            new TradingView.widget({
                "width": "100%",
                "height": "100%",
                "symbol": `BINANCE:${baseSymbol}USDT`,
                "interval": "30",
                "timezone": "Etc/UTC",
                "theme": state.theme === "dark" ? "dark" : "light",
                "style": "1",
                "locale": "en",
                "toolbar_bg": "#181a20",
                "enable_publishing": false,
                "hide_side_toolbar": false,
                "allow_symbol_change": false,
                "container_id": "tradingview_chart"
            });
        } catch (e) {
            renderChartFallback();
        }
    } else {
        renderChartFallback();
    }
}

