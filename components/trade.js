// Auto calculation when user types amounts/price
function setupTradeFormMath() {
    const buyPrice = document.getElementById('buy-price');
    const buyAmount = document.getElementById('buy-amount');
    const buyTotal = document.getElementById('buy-total');
    
    const sellPrice = document.getElementById('sell-price');
    const sellAmount = document.getElementById('sell-amount');
    const sellTotal = document.getElementById('sell-total');

    // Auto-calculates Total on Amount or Price changes
    function calcBuyTotal() {
        const price = activeFormTab === 'limit' ? (parseFloat(buyPrice.value) || 0) : state.tickers[activeTradingPair].price;
        const amount = parseFloat(buyAmount.value) || 0;
        buyTotal.value = (price * amount).toFixed(2);
    }
    buyAmount.addEventListener('input', calcBuyTotal);
    buyPrice.addEventListener('input', calcBuyTotal);

    // Auto-calculates Amount on Total changes
    buyTotal.addEventListener('input', () => {
        const price = activeFormTab === 'limit' ? (parseFloat(buyPrice.value) || 0) : state.tickers[activeTradingPair].price;
        const total = parseFloat(buyTotal.value) || 0;
        if (price > 0) {
            buyAmount.value = (total / price).toFixed(6);
        }
    });

    function calcSellTotal() {
        const price = activeFormTab === 'limit' ? (parseFloat(sellPrice.value) || 0) : state.tickers[activeTradingPair].price;
        const amount = parseFloat(sellAmount.value) || 0;
        sellTotal.value = (price * amount).toFixed(2);
    }
    sellAmount.addEventListener('input', calcSellTotal);
    sellPrice.addEventListener('input', calcSellTotal);

    sellTotal.addEventListener('input', () => {
        const price = activeFormTab === 'limit' ? (parseFloat(sellPrice.value) || 0) : state.tickers[activeTradingPair].price;
        const total = parseFloat(sellTotal.value) || 0;
        if (price > 0) {
            sellAmount.value = (total / price).toFixed(6);
        }
    });

    // Slider percent handlers
    document.querySelectorAll('.buy-slider').forEach(btn => {
        btn.addEventListener('click', () => {
            document.querySelectorAll('.buy-slider').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            
            const pct = parseFloat(btn.dataset.pct);
            const avbl = state.user.balances.USDT;
            const price = activeFormTab === 'limit' ? (parseFloat(buyPrice.value) || state.tickers[activeTradingPair].price) : state.tickers[activeTradingPair].price;
            
            if (price > 0) {
                const total = avbl * pct;
                buyTotal.value = total.toFixed(2);
                buyAmount.value = (total / price).toFixed(6);
            }
        });
    });

    document.querySelectorAll('.sell-slider').forEach(btn => {
        btn.addEventListener('click', () => {
            document.querySelectorAll('.sell-slider').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            
            const pct = parseFloat(btn.dataset.pct);
            const baseSymbol = activeTradingPair.split('/')[0];
            const avbl = state.user.balances[baseSymbol] || 0;
            const price = activeFormTab === 'limit' ? (parseFloat(sellPrice.value) || state.tickers[activeTradingPair].price) : state.tickers[activeTradingPair].price;
            
            const amt = avbl * pct;
            sellAmount.value = amt.toFixed(6);
            sellTotal.value = (amt * price).toFixed(2);
        });
    });

    // Submissions
    document.getElementById('btn-submit-buy').addEventListener('click', processBuyOrder);
    document.getElementById('btn-submit-sell').addEventListener('click', processSellOrder);
}

