// Global Order Cancel handler
window.cancelUserOrder = function(orderId) {
    const index = state.openOrders.findIndex(o => o.id === orderId);
    if (index > -1) {
        const order = state.openOrders[index];
        // Refund
        if (order.side === 'Buy') {
            state.user.balances.USDT += order.total;
        } else {
            const baseSymbol = order.pair.split('/')[0];
            state.user.balances[baseSymbol] += order.amount;
        }

        // Add to history as Cancelled
        state.orderHistory.unshift({
            id: order.id,
            time: new Date().toISOString().replace('T', ' ').slice(0, 19),
            pair: order.pair,
            type: order.type,
            side: order.side,
            price: order.price,
            amount: order.amount,
            total: order.total,
            status: 'Cancelled'
        });

        state.openOrders.splice(index, 1);
        alert('Order Cancelled successfully. Funds refunded.');
        
        saveTradeAppState();
        updateTradeAvblBalances();
        renderUserPanelContent();
        updateHeaderBalance();
    }
};

// Handle live simulated prices on the trading dashboard
window.updateTradeLive = function(changes) {
    changes.forEach(change => {
        if (change.pair === activeTradingPair) {
            // Update Header Stats
            const pLabel = document.getElementById('trade-header-price');
            const cLabel = document.getElementById('trade-header-change');
            const hLabel = document.getElementById('trade-header-high');
            const lLabel = document.getElementById('trade-header-low');
            
            const isPositive = change.change24h >= 0;
            const sign = isPositive ? '+' : '';
            const textClass = isPositive ? 'text-green' : 'text-red';
            
            if (pLabel) {
                pLabel.textContent = `$${change.price.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 4 })}`;
                pLabel.className = `value value-price ${textClass}`;
                
                // Glow flash on change
                pLabel.classList.remove('flash-green-anim', 'flash-red-anim');
                void pLabel.offsetWidth;
                pLabel.classList.add(change.isUp ? 'flash-green-anim' : 'flash-red-anim');
            }
            if (cLabel) {
                cLabel.textContent = `${sign}${change.change24h.toFixed(2)}%`;
                cLabel.className = `value ${textClass}`;
            }

            const ticker = state.tickers[activeTradingPair];
            if (hLabel) hLabel.textContent = `$${ticker.high24h.toLocaleString('en-US', { minimumFractionDigits: 2 })}`;
            if (lLabel) lLabel.textContent = `$${ticker.low24h.toLocaleString('en-US', { minimumFractionDigits: 2 })}`;

            // Update Order Book spread
            const spreadPrice = document.getElementById('ob-spread-price-val');
            const spreadFiat = document.getElementById('ob-spread-fiat');
            if (spreadPrice) {
                spreadPrice.textContent = `$${change.price.toFixed(2)}`;
                spreadPrice.className = `ob-spread-price ${textClass}`;
            }
            if (spreadFiat) {
                spreadFiat.textContent = `=$${change.price.toFixed(2)}`;
            }

            // Adjust order book limits dynamic updates
            // Slighly adjust bids / asks
            baseAsks.forEach((ask, i) => {
                ask.price = change.price * (1 + ((i+1) * 0.0003));
            });
            baseBids.forEach((bid, i) => {
                bid.price = change.price * (1 - ((i+1) * 0.0003));
            });
            renderOrderBookDOM();

            // Inject random fills to trade history feed
            if (Math.random() > 0.4) {
                const amount = Math.random() * 0.9 + 0.001;
                const side = Math.random() > 0.5 ? 'Buy' : 'Sell';
                const timeStr = new Date().toTimeString().split(' ')[0];

                tradesFeed.unshift({
                    price: change.price,
                    amount: amount,
                    side: side,
                    time: timeStr
                });
                if (tradesFeed.length > 30) tradesFeed.pop();
                renderTradeFeedDOM();
            }

            // If user tab is Funds, update values
            if (activeUserTab === 'funds') {
                renderUserPanelContent();
            }

            // Check if open orders can be simulated fill (for demo purposes)
            // Match price logic: if buy order price >= current price, fill it!
            // If sell order price <= current price, fill it!
            let orderFilled = false;
            for (let i = state.openOrders.length - 1; i >= 0; i--) {
                const order = state.openOrders[i];
                if (order.pair === activeTradingPair) {
                    if ((order.side === 'Buy' && order.price >= change.price) || 
                        (order.side === 'Sell' && order.price <= change.price)) {
                        
                        // Fill order
                        if (order.side === 'Buy') {
                            const baseSymbol = order.pair.split('/')[0];
                            state.user.balances[baseSymbol] = (state.user.balances[baseSymbol] || 0) + order.amount;
                        } else {
                            state.user.balances.USDT += order.total;
                        }

                        // Add to history
                        state.orderHistory.unshift({
                            id: order.id,
                            time: new Date().toISOString().replace('T', ' ').slice(0, 19),
                            pair: order.pair,
                            type: order.type,
                            side: order.side,
                            price: order.price,
                            amount: order.amount,
                            total: order.total,
                            status: 'Filled'
                        });

                        state.openOrders.splice(i, 1);
                        orderFilled = true;
                    }
                }
            }

            if (orderFilled) {
                saveTradeAppState();
                updateTradeAvblBalances();
                renderUserPanelContent();
                updateHeaderBalance();
            }
        }
    });
}

